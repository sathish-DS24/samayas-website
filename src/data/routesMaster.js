// Single Source of Truth Exports & Helpers
export const publishedRoutes = routesMasterDataset.filter((r) => r.status === 'Published');
export const routesList = publishedRoutes.map((r) => ({
  ...r,
  fromSlug: r.districtOrigin,
  toSlug: r.districtDestination,
  name: `${r.from} to ${r.to} One-Way Taxi`,
}));

export function getRouteBySlug(slug) {
  if (!slug) return null;
  return routesMasterDataset.find((r) => r.slug.toLowerCase() === slug.toLowerCase()) || null;
}

export function getRouteUrl(slug) {
  return `/one-way-taxi/${slug}`;
}

export function getRoutesFromOrigin(originName) {
  if (!originName) return [];
  const normalized = originName.toLowerCase();
  return routesMasterDataset.filter(
    (r) => r.from.toLowerCase().includes(normalized) || normalized.includes(r.from.toLowerCase())
  );
}

export function findMatchingRouteSlug(fromName, toName) {
  if (!fromName || !toName) return null;
  const match = routesMasterDataset.find(
    (r) =>
      r.status === 'Published' &&
      r.from.toLowerCase().includes(fromName.toLowerCase()) &&
      r.to.toLowerCase().includes(toName.toLowerCase())
  );
  return match ? match.slug : null;
}
